def N(tid, on, dur, pitch, vel, gate=1.0, art=None):
    bar = int((on + 1e-6) // 4) + 1
    k = COUNT.get((tid, bar), 0)
    COUNT[(tid, bar)] = k + 1
    nid = f'{tid}_b{bar:03d}_n{k:02d}'
    n = {'id': nid, 'on': round(on, 5), 'duration': round(dur, 5), 'pitch': int(pitch)}
    if art:
        n['articulation'] = art
    TR[tid]['notes'].append(n)
    TR[tid]['performance']['notes'][nid] = {'velocity': int(max(1, min(127, round(vel)))), 'timing_ms': 0,
                                            'gate': gate}
    return n


TOKEN = re.compile(r'(\[[^\]]*\]|[A-Gr][#b]?-?\d?):([0-9.]+)')


def items(s):
    out = []
    for what, dur in TOKEN.findall(s):
        if what == 'r':
            out.append((None, float(dur)))
        elif what.startswith('['):
            out.append(([P(x) for x in what[1:-1].split()], float(dur)))
        else:
            out.append(([P(what)], float(dur)))
    return out


def length(s):
    return sum(d for _, d in items(s))


def seq(tid, start, s, vel, tr=0, gate=1.0, end_gate=None, art=None):
    """A line (or chords in brackets) written from `start`: 'G4:1.5 G4:.5 [C4 E4]:2 r:1'.  `vel` is a number, a
    function of the beat, or one value per sounding item.  Returns the end beat."""
    its = items(s) if isinstance(s, str) else s
    sounding = [i for i, (ps, _) in enumerate(its) if ps]
    t, k = start, 0
    for i, (ps, d) in enumerate(its):
        if ps:
            v = vel(t) if callable(vel) else vel[k] if isinstance(vel, (list, tuple)) else vel
            g = end_gate if end_gate is not None and i == sounding[-1] else gate
            for p in ps:
                N(tid, t, d, p + tr, v, g, art)
            k += 1
        t += d
    return t


def many(tids, start, s, vel, **kw):
    """The same line on several parts: {'part': (transposition, velocity offset)} or a list of part ids."""
    if not isinstance(tids, dict):
        tids = {t: (0, 0) for t in tids}
    for tid, (tr, dv) in tids.items():
        v = (lambda b, f=vel, d=dv: f(b) + d) if callable(vel) else vel + dv
        seq(tid, start, s, v, tr=tr, **kw)


def dplan(tids, points):
    """Dynamic plan points [(beat, value)] for parts rendered from dynamic layers (the drift inside held notes)."""
    for tid in ([tids] if isinstance(tids, str) else tids):
        DYN[tid] += [(float(b), float(v)) for b, v in points]


def arp(tid, start, nbeats, pitches, vel, step=0.5, ring=1.5, accent=6, span=None):
    """Broken chord: the pitches in the order given, one per `step`, cycling, each left to ring until its harmony
    ends (`span` beats from the start, where that is longer than the figure itself)."""
    k, t = 0, start
    names = pitches.split() if isinstance(pitches, str) else pitches
    end = start + (span or nbeats)
    while t < start + nbeats - 1e-9:
        v = vel(t) if callable(vel) else vel
        onbeat = abs(t - round(t)) < 1e-6
        N(tid, t, max(step, min(ring, end - t)), P(names[k % len(names)]), v + (accent if onbeat else 0))
        t += step
        k += 1


def gliss(tid, start, dur, lo, hi, pcs, v0, v1, down=False, ring=0.5):
    """A harp or piano glissando over the pitch classes `pcs` between two pitches, spread evenly over `dur` beats."""
    ps = [p for p in range(P(lo), P(hi) + 1) if p % 12 in pcs]
    if down:
        ps.reverse()
    n = len(ps)
    for i, p in enumerate(ps):
        N(tid, start + dur * i / n, ring, p, v0 + (v1 - v0) * i / max(n - 1, 1))


def roll(tid, start, dur, pitch, v0, v1, rate=13.0):
    """A roll written out as single strokes, about `rate` a second at the tempo of its start."""
    step = tempo_at(start) / 60.0 / rate
    n = max(2, int(round(dur / step)))
    for i in range(n):
        v = v0 + (v1 - v0) * i / (n - 1)
        N(tid, start + dur * i / n, dur / n, P(pitch) if isinstance(pitch, str) else pitch, v + (2 if i % 2 else -2))


def pad(voice_tids, chords, low, high, vel, against=None, avoid=True, gate=1.0, dv=None):
    """Sustained harmony from `voice_lead`: `chords` is [(start, beats, symbol)], `voice_tids` one part id per voice
    from the lowest.  A voice that keeps its pitch over a change holds it (tied)."""
    syms = [c[2] for c in chords]
    vs = voice_lead(syms, voices=len(voice_tids), low=P(low), high=P(high), against=against, avoid_parallels=avoid)
    for k, tid in enumerate(voice_tids):
        run = None
        for (start, beats, _), voicing in zip(chords, vs):
            p = voicing[k]
            if run and run[2] == p and abs(run[0] + run[1] - start) < 1e-6:
                run[1] += beats
            else:
                if run:
                    N(tid, run[0], run[1], run[2], (vel(run[0]) if callable(vel) else vel) + (dv[k] if dv else 0), gate)
                run = [start, beats, p]
        if run:
            N(tid, run[0], run[1], run[2], (vel(run[0]) if callable(vel) else vel) + (dv[k] if dv else 0), gate)
    return vs


