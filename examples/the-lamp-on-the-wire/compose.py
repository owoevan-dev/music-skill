def pedal(tid, changes, release):
    cc = []
    for k, b in enumerate(changes):
        if k:
            cc.append([round(b, 4), 64, 0])
        cc.append([round(b + 0.08, 4), 64, 127])
    cc.append([round(release, 4), 64, 0])
    TR[tid]['performance'].setdefault('cc', [])
    TR[tid]['performance']['cc'] += cc


