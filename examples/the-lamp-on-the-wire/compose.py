def trsym(sym, k, flat=False):
    names = FLAT if flat else SHARP
    m = re.fullmatch(r'([A-G][#b]?)(.*?)(?:/([A-G][#b]?))?', sym)
    root, qual, bass = m.groups()
    pc = lambda s: (PC[s[0]] + s.count('#') - s.count('b') + k) % 12
    return names[pc(root)] + qual + ('/' + names[pc(bass)] if bass else '')


